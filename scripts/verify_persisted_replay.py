"""End-to-end verification of the persisted local-replay capture.

This proves — against the real processes, not the in-process test transports —
that the ``local-replay`` capture and the content-addressed blob store work
across a process restart:

1. the proxy runs as a separate ``pocket-harness serve`` process with an
   isolated state root and ``capture = "local-replay"``,
2. one request is sent through it, and the run records a ``request.captured``
   event, the canonical request body as a blob, and the content-addressed
   blobs behind the C2 reference stubs,
3. the proxy process is terminated, and the recorded run is replayed with
   fresh ``pocket-harness replay`` processes (one per check, no shared state),
4. the failure modes are exercised deliberately — a missing capture blob, a
   corrupted capture blob, a changed configuration, a tampered payload — and
   none of them may be reported as a success,
5. a positive control shows a deleted content blob is re-derived idempotently,
   because the reference stub carries the digest of the content, not a copy.

The state root lives under ``.e2e/`` (gitignored), carries an isolation marker,
and never touches ``~/.pocket``. The script deletes only its own root and
refuses to reuse an existing one.

Scope note: this verifies the *replay machinery* on a fresh recorded run. It
does NOT re-create the unsaved runs of the 42-task matrix, and it makes no
completion-rate claim.
"""

from __future__ import annotations

import json
import socket
import subprocess
import sys
import threading
import time
from datetime import UTC, datetime
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from httpx import Client, ConnectError  # noqa: E402

from pocket_harness.hashing import canonical_json  # noqa: E402
from pocket_harness.state import StateStore  # noqa: E402

CLI = ROOT / ".venv" / "Scripts" / "pocket-harness.exe"
OUT = ROOT / "docs" / "benchmarks" / "persisted-replay-e2e-2026-10-23.json"
CHAT_MODEL = "test-model"


def _free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def _chat_response() -> dict[str, Any]:
    return {
        "id": "chatcmpl-e2e",
        "object": "chat.completion",
        "model": CHAT_MODEL,
        "choices": [
            {
                "index": 0,
                "message": {"role": "assistant", "content": "ok"},
                "finish_reason": "stop",
            }
        ],
        "usage": {"prompt_tokens": 10, "completion_tokens": 2, "total_tokens": 12},
    }


class _MockUpstream:
    """A canned OpenAI-compatible upstream on localhost."""

    def __init__(self) -> None:
        self.port = _free_port()
        self.requests = 0
        outer = self

        class Handler(BaseHTTPRequestHandler):
            def do_POST(self) -> None:  # noqa: N802 - http.server naming
                length = int(self.headers.get("content-length") or 0)
                self.rfile.read(length)
                outer.requests += 1
                body = canonical_json(_chat_response()).encode("utf-8")
                self.send_response(200)
                self.send_header("content-type", "application/json")
                self.send_header("content-length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)

            def log_message(self, *args: Any) -> None:  # silence
                return None

        self.server = ThreadingHTTPServer(("127.0.0.1", self.port), Handler)
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)

    def start(self) -> None:
        self.thread.start()

    def stop(self) -> None:
        self.server.shutdown()
        self.server.server_close()
        self.thread.join(timeout=5)


def _config_toml(root: Path, proxy_port: int, upstream_port: int) -> str:
    return (
        "# generated by scripts/verify_persisted_replay.py — do not commit\n"
        "[server]\n"
        f'port = {proxy_port}\n\n'
        "[upstream]\n"
        f'base_url = "http://127.0.0.1:{upstream_port}/v1"\n'
        f'model = "{CHAT_MODEL}"\n'
        "context_length = 4096\n\n"
        "[state]\n"
        f'root = "{root.as_posix()}"\n\n'
        "[logging]\n"
        "capture = \"local-replay\"\n"
    )


def _run_cli(*args: str) -> tuple[int, dict[str, Any]]:
    result = subprocess.run(
        [str(CLI), *args],
        capture_output=True,
        text=True,
        check=False,
        cwd=ROOT,
        timeout=120,
    )
    try:
        report = json.loads(result.stdout) if result.stdout.strip() else {}
    except json.JSONDecodeError:
        report = {"_stdout_parse_error": result.stdout[-400:], "stderr": result.stderr[-400:]}
    return result.returncode, report


def _post_with_retry(url: str, body: dict[str, Any], attempts: int = 60) -> Any:
    last_error: Exception | None = None
    for _ in range(attempts):
        try:
            with Client(timeout=10.0) as client:
                return client.post(url, json=body)
        except ConnectError as exc:
            last_error = exc
            time.sleep(0.25)
    raise RuntimeError(f"the proxy never became reachable: {last_error}")


def _request_body() -> dict[str, Any]:
    """A conversation that triggers C4 escalation and C2 dedupe."""
    content = "line of tool output\n" * 260  # > 4 kB, identical three times
    messages: list[dict[str, Any]] = [
        {"role": "system", "content": "you are a coding assistant"},
        {"role": "user", "content": "read a.py"},
    ]
    for index in range(3):
        messages.append(
            {
                "role": "assistant",
                "content": "",
                "tool_calls": [
                    {
                        "id": f"call_{index}",
                        "type": "function",
                        "function": {
                            "name": "read_file",
                            "arguments": canonical_json({"path": "a.py"}),
                        },
                    }
                ],
            }
        )
        messages.append(
            {
                "role": "tool",
                "tool_call_id": f"call_{index}",
                "name": "read_file",
                "content": content,
            }
        )
    return {"model": CHAT_MODEL, "messages": messages}


def _blob_dir(root: Path) -> Path:
    return root / "blobs"


def _blob_path(root: Path, ref: str) -> Path:
    digest = ref.split(":", 1)[-1]
    return _blob_dir(root) / digest


def _main() -> int:
    if not CLI.is_file():
        print(f"the CLI was not found at {CLI}")
        return 1

    stamp = datetime.now(UTC).strftime("%Y%m%d-%H%M%S")
    root = ROOT / ".e2e" / f"persist-replay-{stamp}"
    if root.exists():
        print(f"the isolated root {root} already exists; refusing to reuse it")
        return 1
    root.mkdir(parents=True)
    (root / ".pocket-e2e-isolated").write_text(
        "generated by scripts/verify_persisted_replay.py; safe to delete\n",
        encoding="utf-8",
    )

    config_path = root / "pocket.toml"
    upstream = _MockUpstream()
    upstream.start()
    proxy_port = _free_port()
    config_path.write_text(_config_toml(root, proxy_port, upstream.port), encoding="utf-8")

    report: dict[str, Any] = {
        "date": datetime.now(UTC).isoformat(timespec="seconds"),
        "script": "scripts/verify_persisted_replay.py",
        "commit_under_test": _head(),
        "pipeline_version": _pipeline_version(),
        "upstream": _upstream_manifest(),
        "isolation": {
            "state_root": f".e2e/persist-replay-{stamp}",
            "marker": ".pocket-e2e-isolated",
            "note": "gitignored temporary root created fresh for this run; ~/.pocket untouched",
        },
        "commands": {
            "serve": "pocket-harness serve --config <root>/pocket.toml (separate process)",
            "replay": (
                "pocket-harness replay --config <root>/pocket.toml --run <run_id>"
                " (separate process per check)"
            ),
        },
    }
    failures: list[str] = []

    try:
        with open(root / "serve.out", "w", encoding="utf-8") as serve_log:
            serve = subprocess.Popen(
                [str(CLI), "serve", "--config", str(config_path)],
                stdout=serve_log,
                stderr=subprocess.STDOUT,
                cwd=ROOT,
                creationflags=subprocess.CREATE_NEW_PROCESS_GROUP,  # type: ignore[attr-defined]
            )
            try:
                response = _post_with_retry(
                    f"http://127.0.0.1:{proxy_port}/v1/chat/completions", _request_body()
                )
                report["record_phase"] = {"post_status": response.status_code}
                if response.status_code != 200:
                    failures.append(f"the POST through the proxy returned {response.status_code}")
                    report["record_phase"]["post_body"] = response.text[:400]
                time.sleep(1.5)  # let the events flush
            finally:
                serve.terminate()
                try:
                    serve.wait(timeout=15)
                except subprocess.TimeoutExpired:
                    serve.kill()
                    serve.wait(timeout=15)
                    failures.append("the proxy process had to be killed")
                report["serve_exit_code"] = serve.returncode

        store = StateStore(root)
        runs = store.list_runs()
        if not runs:
            print("no run was recorded in the isolated store")
            return _finish(report, failures + ["no run was recorded"])
        run_id = runs[0]["run_id"]
        manifest = runs[0]["manifest"]
        events = list(store.iter_events(run_id))
        captured = [e for e in events if e["event"] == "request.captured"]
        transformed = [e for e in events if e["event"] == "request.transformed"]
        if not captured or not captured[0].get("payload", {}).get("blob_ref"):
            failures.append("no request.captured event with a blob reference was recorded")
        captured_ref = (captured[0].get("payload") or {}).get("blob_ref") if captured else None
        captured_hex = (captured_ref or "").split(":", 1)[-1]
        captured_path = _blob_path(root, captured_ref) if captured_ref else None
        if captured_path is None or not captured_path.is_file():
            failures.append("the captured request blob is not on disk")
        if manifest.get("config_hash") is None or manifest.get("capture") != "local-replay":
            failures.append(f"the run manifest is incomplete: {sorted(manifest)}")
        content_blobs = [
            p.name for p in _blob_dir(root).iterdir() if p.name != captured_hex
        ]
        record = transformed[0].get("payload") or {}
        report["record_phase"].update(
            {
                "run_id": run_id,
                "manifest": manifest,
                "request_captured": True if captured else False,
                "captured_blob_ref": captured_ref,
                "captured_blob_on_disk": bool(captured_path and captured_path.is_file()),
                "content_blobs": len(content_blobs),
                "event_count": len(events),
                "recorded_rules": [r.get("id") for r in record.get("rules") or []],
                "recorded_input_sha256": record.get("input_sha256"),
                "recorded_output_sha256": record.get("output_sha256"),
            }
        )
        if len(transformed) != 1:
            failures.append(f"expected exactly one request.transformed, got {len(transformed)}")
        if not any(r.get("id") == "C4.repeat_warning" for r in record.get("rules") or []):
            failures.append("the recorded request did not carry the C4 escalation rule")
        if not any(r.get("id") == "C2.dedupe" for r in record.get("rules") or []):
            failures.append("the recorded request did not carry the C2 dedupe rule")

        # ---------------------------------------------------- fresh-process replay
        code, replayed = _run_cli("replay", "--config", str(config_path), "--run", run_id)
        report["replay_phase"] = {
            "new_process": True,
            "exit_code": code,
            "ok": replayed.get("ok"),
            "input_matched": replayed.get("input_matched"),
            "config_matched": replayed.get("config_matched"),
            "matched": replayed.get("matched"),
            "rules": replayed.get("rules"),
            "replayed_input_sha256": replayed.get("replayed_input_sha256"),
            "replayed_output_sha256": replayed.get("replayed_output_sha256"),
            "config_hash": replayed.get("config_hash"),
            "recorded_config_hash": replayed.get("recorded_config_hash"),
            "content_ref_note": (
                "the output hash equality covers the C2 stubs byte for byte, including "
                "their content_ref digests; the blob dependency itself is exercised by "
                "the scenario controls below"
            ),
        }
        if code != 0 or not replayed.get("ok"):
            failures.append(f"the fresh-process replay did not succeed: {replayed.get('reason')}")
        if replayed.get("rules") != report["record_phase"]["recorded_rules"]:
            failures.append("the replayed rule order differs from the recorded rule order")
        if replayed.get("replayed_input_sha256") != report["record_phase"]["recorded_input_sha256"]:
            failures.append("the replayed input hash differs")
        if replayed.get("replayed_output_sha256") != report["record_phase"]["recorded_output_sha256"]:
            failures.append("the replayed output hash differs")

        # ------------------------------------------- positive control: content blob
        control: dict[str, Any] = {"expect": "ok: the reference stub is digested, not a copy"}
        if content_blobs and captured_path is not None:
            blob_file = _blob_dir(root) / content_blobs[0]
            blob_file.unlink()
            code, replayed = _run_cli("replay", "--config", str(config_path), "--run", run_id)
            control.update(
                {
                    "deleted_blob": content_blobs[0],
                    "recreated": blob_file.is_file(),
                    "ok": replayed.get("ok"),
                    "matched": replayed.get("matched"),
                }
            )
            if code != 0 or not replayed.get("ok"):
                failures.append(
                    "the content-blob control failed: a deleted content blob made the "
                    "replay fail although the reference stub carries the digest"
                )
        else:
            control["skipped"] = "no content blob was recorded"
            failures.append("no content blob was recorded next to the capture")
        report["content_blob_control"] = control

        # --------------------------------------------------- deliberate failures
        scenarios: dict[str, Any] = {}
        if captured_path is not None:
            original = captured_path.read_bytes()

            def _restore() -> None:
                captured_path.write_bytes(original)

            # (a) the capture blob is missing entirely
            captured_path.unlink()
            code, replayed = _run_cli("replay", "--config", str(config_path), "--run", run_id)
            _restore()
            scenarios["missing_capture_blob"] = {
                "expect": "fails: nothing can be replayed without the stored body",
                "ok": replayed.get("ok"),
                "reason": replayed.get("reason"),
            }
            if replayed.get("ok") or "no capture found" not in str(replayed.get("reason")):
                failures.append("the missing-blob scenario did not fail as expected")

            # (b) the capture blob is corrupted
            captured_path.write_bytes(b"this is not json")
            code, replayed = _run_cli("replay", "--config", str(config_path), "--run", run_id)
            _restore()
            scenarios["corrupt_capture_blob"] = {
                "expect": "fails: the stored body is not valid JSON",
                "ok": replayed.get("ok"),
                "reason": replayed.get("reason"),
            }
            if replayed.get("ok") or "not valid JSON" not in str(replayed.get("reason")):
                failures.append("the corrupt-blob scenario did not fail as expected")

            # (d) the stored body was tampered with
            payload = json.loads(original.decode("utf-8"))
            inner = payload["payload"] if isinstance(payload, dict) and "payload" in payload else payload
            for message in inner["messages"]:
                if message["role"] == "user":
                    message["content"] = f"{message['content']} tampered"
                    break
            captured_path.write_bytes(canonical_json(payload).encode("utf-8"))
            code, replayed = _run_cli("replay", "--config", str(config_path), "--run", run_id)
            _restore()
            scenarios["tampered_payload"] = {
                "expect": "fails: input hash and output hash both differ",
                "ok": replayed.get("ok"),
                "input_matched": replayed.get("input_matched"),
                "matched": replayed.get("matched"),
            }
            if replayed.get("ok") or replayed.get("input_matched"):
                failures.append("the tampered-payload scenario did not fail as expected")
        else:
            failures.append("the failure scenarios were skipped: no capture blob")

        # (c) the configuration changed between record and replay
        config2 = root / "pocket-changed.toml"
        config2.write_text(
            _config_toml(root, proxy_port, upstream.port).replace(
                "context_length = 4096", "context_length = 8192"
            ),
            encoding="utf-8",
        )
        code, replayed = _run_cli("replay", "--config", str(config2), "--run", run_id)
        scenarios["changed_configuration"] = {
            "expect": "fails: the recorded config hash differs from the replay one",
            "ok": replayed.get("ok"),
            "config_matched": replayed.get("config_matched"),
            "matched": replayed.get("matched"),
            "warning": (replayed.get("warnings") or [None])[0],
        }
        if replayed.get("ok") or replayed.get("config_matched") is not False:
            failures.append("the changed-configuration scenario did not fail as expected")
        report["failure_scenarios"] = scenarios
    finally:
        upstream.stop()

    print(json.dumps({"written": str(OUT), "failures": failures}, indent=2))
    return _finish(report, failures)


def _finish(report: dict[str, Any], failures: list[str]) -> int:
    report["scope_note"] = (
        "verifies the replay machinery on a freshly recorded run only; the unsaved "
        "42-task matrix runs stay unverified and no completion-rate claim is made"
    )
    report["summary"] = {
        "scenarios": len(report.get("failure_scenarios") or {}) + 2,
        "failures": len(failures),
        "all_passed": not failures,
    }
    OUT.write_text(canonical_json(report) + "\n", encoding="utf-8")
    return 0 if not failures else 1


def _head() -> str:
    result = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"],
        capture_output=True,
        text=True,
        check=False,
        cwd=ROOT,
    )
    return result.stdout.strip() or "unknown"


def _pipeline_version() -> str:
    from pocket_harness.version import PIPELINE_VERSION

    return PIPELINE_VERSION


def _upstream_manifest() -> dict[str, Any]:
    import platform

    return {
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "mock_upstream": "in-process canned OpenAI-compatible HTTP server",
    }


if __name__ == "__main__":
    raise SystemExit(_main())
